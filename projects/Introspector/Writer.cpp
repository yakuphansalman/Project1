#include "Writer.hpp"

#include "Reader.hpp"

Writer::Writer() {
    std::cout << "WRITER INITIALIZED" << std::endl;
}

void Writer::writeClass(std::string className,std::string parent, std::vector<Property> *classProps) {
    std::cout << "WRITING CLASS " << className << std::endl;

    std::string nspace = parent;
    *nspace.begin() = *nspace.begin() + 'A' - 'a';

    _include-> ss << "#include \""<< parent << "/" << className << ".hpp\"" << std::endl;

    for (Property prop : *classProps) {
        _function-> ss << "\tprops.push_back(REGISTER_PROPERTY("
        << prop.name << ", "
        << prop.type << ", "
        << nspace << "::" << className << "));" << std::endl;
    }
    _function-> ss << "\t_classMap[\"" << className << "\"] = props;" << std::endl
    << "\tprops.clear();" << std::endl;

}

void Writer::writeGenerated(std::string generatedPath) {
    std::ofstream file(generatedPath) ;

    if (!file.is_open()) {
        std::cerr << "ERROR: Could not open file " << generatedPath << std::endl;
        return;
    }

    file << "//THIS SCRIPT GENERATED BY INTROSPECTOR" << std::endl
    << "#include \"Generated.hpp\"" << std::endl
    << _include->ss.str() << std::endl
    << "void Generated::RegisterAllProperties(){" << std::endl
    << _function->ss.str() << std::endl
    << "}" << std::endl;

    file.close();
}




